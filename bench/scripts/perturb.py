"""Generate answer-preserving perturbations of math problems, mimicking the official families.

Families (styles copied from the public aimo-interp samples):
  typos     rule-based character noise in plain words only (never inside $...$ or digits)
  rephrase  same story, same names, reworded sentences
  rename    rename people/places/objects/variables, keep the story
  domain    move the problem into a different real-world setting, keep every number and relation
  distract  add one irrelevant but true/consistent clause that does not change the answer
  expert_perturbations  add one plausible-looking numeric side condition that the intended configuration
                        satisfies (answer unchanged)                       [needs --answers]
  expert_no_solution    add one plausible-looking condition that contradicts the setup (answer becomes NaN)
                        [needs --answers]
  expert_modify         expert-style modification that CHANGES the answer: ask for a closely related quantity or
                        add one more step on top of the same core argument (official examples: "length of BE" ->
                        "square of the area of BXE"; S(...) nested once more). The generator proposes the new
                        answer; the judge solves the variant from scratch and it is kept only if they agree.
                        [needs --answers]
LLM families are generated by an OpenAI-compatible server, then judged by a (possibly different) judge model:
equivalence for the plain families, "condition holds" / "condition contradicts" for the expert ones (the judge
sees the reference answer). Only accepted variants have `ok=True`.

Output jsonl: {id, family, j, problem, answer, ok, judge, gen_model}; `answer` is the variant's expected
answer (the original's, or "NaN" for expert_no_solution; null if no --answers).
"""
