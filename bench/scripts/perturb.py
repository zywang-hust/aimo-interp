class _Done(Exception):
    pass


_MATH = re.compile(r"(\$\$.*?\$\$|\$.*?\$|\\\(.*?\\\)|\\\[.*?\\\]|\\begin\{.*?\\end\{[^}]*\})", re.S)


def typo_word(w, rng):
    if len(w) < 4 or not w.isalpha():
        return w
    i = rng.randrange(1, len(w) - 2)
    op = rng.choice(["swap", "drop", "dup", "swap"])
    if op == "swap":
        return w[:i] + w[i + 1] + w[i] + w[i + 2:]
    if op == "drop":
        return w[:i] + w[i + 1:]
    return w[:i] + w[i] + w[i:]


def make_typos(text, seed, rate=0.12):
    """Corrupt ~rate of the plain-text words; math segments and anything with digits are left intact."""
    rng = random.Random(seed)
    parts = _MATH.split(text)
    out = []
    for k, part in enumerate(parts):
        if k % 2 == 1:  # math segment
            out.append(part)
            continue
        toks = re.split(r"(\s+)", part)
        out.append("".join(typo_word(t, rng) if (not t.isspace() and rng.random() < rate) else t for t in toks))
    s = "".join(out)
    if rng.random() < 0.5:  # duplicated punctuation, as in the official samples
        s = re.sub(r"\.(\s)", lambda m: ".." + m.group(1) if rng.random() < 0.3 else m.group(0), s, count=2)
    return s


def chat(base_url, model, prompt, max_tokens, temperature=0.7, extra=None):
    payload = {"model": model, "messages": [{"role": "user", "content": prompt}],
               "max_tokens": max_tokens, "temperature": temperature}
    if extra:
        payload.update(extra)
    req = urllib.request.Request(base_url.rstrip("/") + "/chat/completions", data=json.dumps(payload).encode(),
                                 headers={"Content-Type": "application/json"})
    opener = urllib.request.build_opener(urllib.request.ProxyHandler({}))
    with opener.open(req, timeout=3600) as r:
        return json.load(r)["choices"][0]["message"]["content"] or ""


def clean(text):
    text = re.sub(r"^(here is|rewritten problem|problem)\s*[:：-]*\s*", "", text.strip(), flags=re.I)
    return text.strip().strip("`").strip()


async def run_one(sem, args, row, fam, j, out_f, lock):
    loop = asyncio.get_running_loop()
    rec = {"id": row["id"], "family": fam, "j": j, "gen_model": args.gen_model if fam != "typos" else "rule"}
    ref = args.ref.get(row["id"])
    rec["answer"] = "NaN" if fam.startswith("expert_no_solution") and ref is not None else ref
    async with sem:
        try:
            if fam == "typos":
                new = make_typos(row["problem"], seed=hash((row["id"], j)) % 2**31)
            else:
                if fam == "expert_modify":
                    if ref is None:
                        raise ValueError("expert families need --answers")
                    raw = await loop.run_in_executor(None, chat, args.gen_url, args.gen_model,
                                                     MODIFY_PROMPT.format(answer=ref, problem=row["problem"]),
                                                     args.gen_max_tokens, 0.8, json.loads(args.gen_extra or "{}"))
                    m = re.search(r"\{.*\}", raw or "", re.S)
                    obj = json.loads(m.group(0)) if m else {}
                    new = (obj.get("problem") or "").strip()
                    rec.update(answer=normalize(str(obj.get("answer"))), change=obj.get("change"))
                    sol = await loop.run_in_executor(None, chat, args.judge_url, args.judge_model,
                                                     SOLVE_PROMPT.format(problem=new), max(args.judge_max_tokens, 32768),
                                                     1.0, json.loads(args.judge_extra or "{}"))
                    got = extract_answer(sol)[1]
                    rec.update(problem=new, judge_answer=got, judge="solve",
                               ok=bool(new) and rec["answer"] is not None and got == rec["answer"] and got != normalize(ref))
                    raise _Done
                if fam in EXPERT_PROMPTS:
                    if ref is None:
                        raise ValueError("expert families need --answers")
                    prompt = EXPERT_PROMPTS[fam].format(answer=ref) + GEN_SUFFIX.format(problem=row["problem"])
                else:
                    prompt = GEN_PROMPTS[fam] + GEN_SUFFIX.format(problem=row["problem"])
                new = clean(await loop.run_in_executor(None, chat, args.gen_url, args.gen_model, prompt,
                                                       args.gen_max_tokens, 0.8, json.loads(args.gen_extra or "{}")))
            rec["problem"] = new
            if fam == "typos" or args.no_judge:
                rec.update(ok=bool(new), judge="skip")
            else:
                jt = await loop.run_in_executor(None, chat, args.judge_url, args.judge_model,
                                                (EXPERT_JUDGE[fam].format(orig=row["problem"], new=new, answer=ref)
                                                 if fam in EXPERT_JUDGE else
                                                 JUDGE_PROMPT.format(orig=row["problem"], new=new)),
                                                args.judge_max_tokens, 0.0, json.loads(args.judge_extra or "{}"))
                v = re.findall(r"VERDICT:\s*(EQUIVALENT|DIFFERENT)", jt or "")
                rec.update(ok=bool(v) and v[-1] == "EQUIVALENT", judge=v[-1] if v else "none")
        except _Done:
            pass
        except Exception as e:
            rec.update(ok=False, error=str(e)[:300])
    async with lock:
        out_f.write(json.dumps(rec, ensure_ascii=False) + "\n")
        out_f.flush()


async def main_async(args):
    # the default executor caps at min(32, cpus+4) threads, which silently capped concurrency at 32
    asyncio.get_running_loop().set_default_executor(ThreadPoolExecutor(max_workers=args.concurrency + 8))
    rows = [json.loads(l) for l in open(args.input) if l.strip()]
    args.ref = {}
    if args.answers:
        args.ref = {r["id"]: str(r["answer"]) for r in map(json.loads, open(args.answers)) if r.get("answer") is not None}
    done = set()
    if os.path.exists(args.out):
        for l in open(args.out):
            r = json.loads(l)
            if "error" not in r:
                done.add((r["id"], r["family"], r["j"]))
    fams = args.families.split(",")
    todo = [(r, f, j) for r in rows for f in fams for j in range(args.k) if (r["id"], f, j) not in done]
    print(f"{len(todo)} variants to generate", file=sys.stderr)
    sem, lock = asyncio.Semaphore(args.concurrency), asyncio.Lock()
    with open(args.out, "a") as out_f:
        await asyncio.gather(*(run_one(sem, args, r, f, j, out_f, lock) for r, f, j in todo))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--input", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--families", default=",".join(FAMILIES))
    ap.add_argument("--answers", default=None, help="jsonl {id, answer}; required for the expert families")
    ap.add_argument("--k", type=int, default=3, help="variants per family")
    ap.add_argument("--gen-url", required=True)
    ap.add_argument("--gen-model", required=True)
    ap.add_argument("--gen-extra", default=None)
    ap.add_argument("--gen-max-tokens", type=int, default=8192)
    ap.add_argument("--judge-url")
    ap.add_argument("--judge-model")
    ap.add_argument("--judge-extra", default=None)
    ap.add_argument("--judge-max-tokens", type=int, default=8192)
    ap.add_argument("--no-judge", action="store_true")
    ap.add_argument("--concurrency", type=int, default=64)
    args = ap.parse_args()
    if not args.no_judge and not (args.judge_url and args.judge_model):
        ap.error("--judge-url/--judge-model required unless --no-judge")
    asyncio.run(main_async(args))


if __name__ == "__main__":
    main()
